def test_q4_rules():
    validate_rules(q4, 4)


def test_q4_recursion_executed():
    assert_recursion_executed(q4, q4.flatten_eidi, ([2000, [3000, 4000]],))


@pytest.mark.parametrize('envelope, expected, visible', q4_testcases)
def test_q4(envelope, expected, visible):
    original = copy.deepcopy(envelope)
    result = q4.flatten_eidi(envelope)
    assert isinstance(result, list), "Return a list."
    assert envelope == original, "Do not modify envelope."
    assert result is not envelope, "Return a NEW list."
    if visible:
        assert result == expected
    else:
        assert hashlib.sha256(str(result).encode("utf-8")).hexdigest() == expected
